"""
Regenerates ImplantMaterialID/Models/PercentileReferenceData.cs from the phantom
characterisation CSV in this folder.

Usage (from the repository root, Python 3, standard library only):

    python calibration/generate_reference_data.py

Expected CSV layout (one row per contoured rod), as exported by the site's HU-percentile
script:
  - StructureSet starts with "SS" (stainless steel) or "Ti" (titanium).
  - Structure is "<diameter>mm_<threshold>", e.g. "04mm_1500" = 4 mm rod contoured with a
    1500 HU threshold.
  - PixelSizeX_mm / PixelSizeY_mm give the in-plane pixel size.
  - P70_HU / P80_HU / P90_HU are linear-interpolation percentiles (Excel PERCENTILE.INC /
    numpy default) of the voxel HU values inside the structure.

The script fails loudly if the grid is incomplete (every material must have every
diameter x pixel size x threshold combination), because the trilinear lookup needs a full
rectangular grid.
"""

import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "Combined_HU_percentiles.csv")
OUT_PATH = os.path.join(HERE, "..", "ImplantMaterialID", "Models", "PercentileReferenceData.cs")

MATERIALS = {"SS": "StainlessSteel", "Ti": "Titanium"}
PERCENTILES = ["P70", "P80", "P90"]


def load_rows(path):
    rows = []
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            material = r["StructureSet"][:2]
            if material not in MATERIALS:
                sys.exit(f"Unrecognised material prefix in StructureSet '{r['StructureSet']}'")
            dia_text, thr_text = r["Structure"].split("_")
            px, py = float(r["PixelSizeX_mm"]), float(r["PixelSizeY_mm"])
            if abs(px - py) > 1e-6:
                sys.exit(f"Non-square pixels in row {r}")
            rows.append({
                "material": material,
                "diameter": float(dia_text.replace("mm", "")),
                "threshold": float(thr_text),
                "pixel": px,
                **{p: float(r[f"{p}_HU"]) for p in PERCENTILES},
            })
    return rows


def build_grids(rows):
    diameters = sorted({r["diameter"] for r in rows})
    pixels = sorted({r["pixel"] for r in rows})
    thresholds = sorted({r["threshold"] for r in rows})

    grids = {}
    for material in MATERIALS:
        for p in PERCENTILES:
            grid = [[[None] * len(thresholds) for _ in pixels] for _ in diameters]
            for r in rows:
                if r["material"] != material:
                    continue
                i, j, k = diameters.index(r["diameter"]), pixels.index(r["pixel"]), thresholds.index(r["threshold"])
                if grid[i][j][k] is not None:
                    sys.exit(f"Duplicate row for {material} {r['diameter']}mm {r['pixel']}mm {r['threshold']}HU")
                grid[i][j][k] = r[p]
            for i, d in enumerate(diameters):
                for j, px in enumerate(pixels):
                    for k, t in enumerate(thresholds):
                        if grid[i][j][k] is None:
                            sys.exit(f"Missing row for {material} {d}mm {px}mm {t}HU")
            grids[(material, p)] = grid
    return diameters, pixels, thresholds, grids


def fmt(v):
    return f"{v:g}"


def render(diameters, pixels, thresholds, grids):
    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by calibration/generate_reference_data.py from calibration/Combined_HU_percentiles.csv.")
    w("// Do not edit by hand - change the CSV and re-run the script instead.")
    w("// </auto-generated>")
    w("namespace ImplantMaterialID.Models")
    w("{")
    w("    /// <summary>")
    w("    /// Phantom characterisation of the upper HU percentiles of stainless steel and titanium rods,")
    w("    /// indexed [diameterIndex, pixelSizeIndex, thresholdIndex]. Only valid for the scanner,")
    w("    /// protocol and reconstruction the phantom was scanned with - see README.")
    w("    /// </summary>")
    w("    public static class PercentileReferenceData")
    w("    {")
    w("        /// <summary>Rod diameters (mm), ascending.</summary>")
    w(f"        public static readonly double[] DiametersMm = {{ {', '.join(fmt(d) for d in diameters)} }};")
    w("")
    w("        /// <summary>In-plane pixel sizes (mm), ascending.</summary>")
    w(f"        public static readonly double[] PixelSizesMm = {{ {', '.join(fmt(p) for p in pixels)} }};")
    w("")
    w("        /// <summary>HU thresholds used to create the structures, ascending.</summary>")
    w(f"        public static readonly double[] ThresholdsHu = {{ {', '.join(fmt(t) for t in thresholds)} }};")
    for material, name in MATERIALS.items():
        for p in PERCENTILES:
            grid = grids[(material, p)]
            w("")
            w(f"        public static readonly double[,,] {name}{p}Hu =")
            w("        {")
            for i, d in enumerate(diameters):
                w(f"            // {fmt(d)} mm; rows = pixel size {', '.join(fmt(x) for x in pixels)}; columns = threshold {', '.join(fmt(t) for t in thresholds)}")
                w("            {")
                for j in range(len(pixels)):
                    w("                { " + ", ".join(fmt(v) for v in grid[i][j]) + " },")
                w("            },")
            w("        };")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def main():
    rows = load_rows(CSV_PATH)
    diameters, pixels, thresholds, grids = build_grids(rows)
    with open(OUT_PATH, "w", newline="\n") as f:
        f.write(render(diameters, pixels, thresholds, grids))
    print(f"Wrote {os.path.normpath(OUT_PATH)} from {len(rows)} rows "
          f"({len(diameters)} diameters x {len(pixels)} pixel sizes x {len(thresholds)} thresholds).")


if __name__ == "__main__":
    main()
